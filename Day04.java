public class BilanganBulat {
    public static void main(String[] args) {

        // Tipe data byte
        byte umur = 18;

        // Tipe data short
        short jumlahSiswa = 500;

        // Tipe data int
        int harga = 1500000;

        // Tipe data long
        long jumlahPenduduk = 8000000000L;

        // Menampilkan data
        System.out.println("=== TIPE DATA BILANGAN BULAT ===");
        System.out.println("Byte           : " + umur);
        System.out.println("Short          : " + jumlahSiswa);
        System.out.println("Int            : " + harga);
        System.out.println("Long           : " + jumlahPenduduk);
    }
}

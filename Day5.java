public class Pecahan {
    public static void main(String[] args) {

        // Tipe data double
        double tinggi = 170.5;
        double berat = 60.75;

        // Tipe data float
        float nilai = 89.5f;
        float suhu = 36.5f;

        System.out.println("Tinggi badan : " + tinggi + " cm");
        System.out.println("Berat badan  : " + berat + " kg");

        System.out.println("Nilai        : " + nilai);
        System.out.println("Suhu         : " + suhu + " °C");
    }
}
